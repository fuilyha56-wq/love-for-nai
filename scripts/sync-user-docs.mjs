import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "docs/user-guide");
const manifest = JSON.parse(await readFile(path.join(source, "manifest.json"), "utf8"));
const guides = await Promise.all(manifest.guides.map(async (guide) => ({
  ...guide,
  content: (await readFile(path.join(source, `${guide.slug}.md`), "utf8")).replaceAll("\r\n", "\n").trim(),
})));
if (new Set(guides.map((guide) => guide.slug)).size !== guides.length || new Set(guides.map((guide) => guide.id)).size !== guides.length) throw new Error("Duplicate documentation ID or slug");
const generated = `// Generated by scripts/sync-user-docs.mjs from docs/user-guide/.\n// Edit the Markdown sources, then run the generator.\nexport const DOCUMENTATION_REVISION = ${manifest.revision};\nexport const documentationGuides = ${JSON.stringify(guides, null, 2)};\nexport const currentDocumentation: Record<string, string> = Object.fromEntries(documentationGuides.map((guide) => [guide.slug, guide.content]));\n`;
const target = path.join(root, "src/lib/documentation-content.ts");
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== generated) throw new Error("User guides are out of sync; run node scripts/sync-user-docs.mjs");
  console.log(`${guides.length} user guides are synchronized`);
} else {
  await writeFile(target, generated, "utf8");
  console.log(`Updated ${guides.length} user guides (revision ${manifest.revision})`);
}
