/* eslint-disable @typescript-eslint/no-require-imports -- Local browser acceptance for the outpaint tutorial. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');
process.env.LFN_UI_BASE_URL ||= 'http://127.0.0.1:3000';
process.env.LFN_PLAYWRIGHT_MODULE ||= path.resolve('.tmp/browser-check/node_modules/playwright-core');
process.env.LFN_UI_TEST_SESSION_SECRET ||= 'lfn-local-tutorial-ui-test-secret-only-20261026';
require('@next/env').loadEnvConfig(process.cwd(), true, { info() {}, error() {} });
const { setup, chromium, baseURL } = require('./check-mobile-ui.cjs');
const output = path.resolve('public/tutorials/outpaint');
fs.mkdirSync(output, { recursive: true });
const mobileOutput = path.resolve('.tmp/outpaint-mobile-audit');
fs.mkdirSync(mobileOutput, { recursive: true });

(async () => {
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="384" height="512"><rect width="384" height="512" fill="#d4e8f5"/><circle cx="300" cy="90" r="40" fill="#ffe5a0"/><path d="M0 512V340L120 170L230 340L300 260L384 380V512Z" fill="#75a68b"/><path d="M0 512V410L160 290L300 440L384 380V512Z" fill="#42756c"/></svg>';
  const source = await sharp(Buffer.from(svg)).png().toBuffer();
  const browser = await chromium.launch({ headless: true, channel: process.env.LFN_UI_BROWSER_CHANNEL || 'msedge' });
  const { context, page, requests } = await setup(browser, { theme: 'paper', workspaceLayout: 'lfn' }, { width: 1440, height: 1000 });
  page.setDefaultTimeout(20000);
  page.setDefaultNavigationTimeout(90000);
  const pageErrors = [];
  const externalWrites = [];
  let mobileModeSwitch = { passed: false, issue: null };
  page.on('pageerror', error => pageErrors.push(error.stack || error.message));
  await context.route('**/api/images/operate', async route => {
    externalWrites.push(route.request().postDataJSON());
    const candidate = await sharp(source).resize(384, 512).png().toBuffer();
    await route.fulfill({ json: { images: [`data:image/png;base64,${candidate.toString('base64')}`], historyIds: [], payment: 'aff' } });
  });
  const snap = async n => {
    await page.waitForTimeout(400);
    await page.screenshot({ path: path.join(output, `step-${String(n).padStart(2, '0')}.png`), animations: 'disabled' });
  };
  const expandTutorial = async () => { const button = page.getByRole('button', { name: '展开教程说明', exact: true }); if (await button.count()) await button.click(); };
  const collapseTutorial = async () => { const button = page.getByRole('button', { name: '收起说明，继续操作', exact: true }); if (await button.count()) await button.first().click(); };
  const advanceTutorial = async targetPage => {
    const footer = targetPage.locator('.feature-tutorial-panel footer');
    const editorNext = footer.getByRole('button', { name: /已进入编辑器，继续/ });
    if (await editorNext.count()) await editorNext.click();
    else await footer.getByRole('button', { name: /下一步/ }).click();
  };
  try {
    await page.goto(`${baseURL}/profile#profile-tutorials`);
    const card = page.locator('[data-tutorial-id="outpaint"]');
    await card.getByRole('button', { name: /手把手教程$/ }).click();
    await page.waitForURL('**/image');
    await page.locator('.feature-tutorial-panel h2').getByText('选择重绘模式并上传源图', { exact: true }).waitFor();
    await page.getByRole('button', { name: '收起说明，继续操作', exact: true }).first().click();
    const modePicker = page.getByRole('button', { name: /当前.*点击选择生成模式/ }).filter({ visible: true }).first();
    await modePicker.click();
    let inpaintOption = page.getByRole('option').filter({ hasText: /局部重绘/ }).first();
    if (await inpaintOption.count()) await inpaintOption.click();
    else await page.getByRole('dialog', { name: '选择生成模式', exact: true }).getByRole('button').filter({ hasText: /局部重绘/ }).first().click();
    await page.waitForTimeout(300);
    const sourceInput = page.locator('[data-tutorial="source"] input[type="file"], .mobile-studio-reference-panel input[type="file"]').first();
    await sourceInput.setInputFiles({ name: 'outpaint-practice.png', mimeType: 'image/png', buffer: source });
    await page.waitForFunction(() => document.documentElement.dataset.tutorialSourceReady === 'true' || document.querySelector('[data-tutorial-source-ready="true"]'));
    await snap(1);
    await expandTutorial();
    await page.locator('.feature-tutorial-panel footer').getByRole('button', { name: /下一步/ }).click();
    await page.locator('.feature-tutorial-panel h2').getByText('打开无限画布', { exact: true }).waitFor();
    await page.waitForFunction(() => document.querySelector('[data-feature-tutorial-target="true"]')?.matches('button[data-tutorial-editor="canvas"]'));
    assert.equal(await page.locator('[data-feature-tutorial-target="true"]').getAttribute('data-tutorial-editor'), 'canvas', 'Entry step must highlight the actual canvas editor button');
    await snap(2);
    const sourceTarget = page.locator('button[data-tutorial-editor="canvas"]:visible').first();
    await sourceTarget.click();
    await page.waitForURL('**/image/editor?**');
    await page.locator('.editor-stage canvas').first().waitFor();
    const draftId = new URL(page.url()).searchParams.get('draftId');
    assert(draftId, 'Uploaded source must be retained in a persisted editor draft');
    await expandTutorial();
    await advanceTutorial(page);
    await page.locator('.feature-tutorial-panel h2').getByText('把生成框移到画面外', { exact: true }).waitFor();
    const stage = await page.locator('.editor-stage').boundingBox();
    const corner = await page.locator('.viewport-corner.se').boundingBox();
    assert(stage && corner, 'Canvas editor and viewport corner must be visible');
    await page.mouse.move(corner.x + corner.width / 2, corner.y + corner.height / 2);
    await page.mouse.down();
    await page.mouse.move(Math.min(stage.x + stage.width - 50, corner.x + corner.width / 2 + 130), Math.min(stage.y + stage.height - 50, corner.y + corner.height / 2 + 100), { steps: 12 });
    await page.mouse.up();
    assert.equal(new URL(page.url()).searchParams.get('draftId'), draftId, 'The editor retains the uploaded source draft');
    await snap(3);
    await expandTutorial();
    await advanceTutorial(page);
    await page.locator('.feature-tutorial-panel h2').getByText('描述要补出的画面', { exact: true }).waitFor();
    assert.equal(new URL(page.url()).searchParams.get('draftId'), draftId);
    await snap(4);
    await expandTutorial();
    await advanceTutorial(page);
    await page.locator('.feature-tutorial-panel h2').getByText('生成并检查接缝', { exact: true }).waitFor();
    await collapseTutorial();
    await page.locator('.editor-actions').getByRole('button', { name: '生成并预览', exact: true }).click();
    await page.locator('.editor-actions').getByRole('button', { name: '应用到工作台', exact: true }).waitFor();
    assert.equal(externalWrites.length, 1, 'Only the explicit preview click invokes the intercepted generation API');
    assert.equal(externalWrites[0].operation, 'outpainting');
    await snap(5);
    await expandTutorial();
    await advanceTutorial(page);
    await page.locator('.feature-tutorial-panel h2').getByText('应用或下载扩图', { exact: true }).waitFor();
    await collapseTutorial();
    await page.locator('.editor-actions').getByRole('button', { name: '应用到工作台', exact: true }).click();
    await page.waitForURL('**/image?**');
    await expandTutorial();
    await page.getByRole('button', { name: '完成教程，返回教程中心', exact: true }).click();
    await page.waitForURL('**/profile#profile-tutorials');
    await page.locator('[data-tutorial-id="outpaint"] .tutorial-completed').waitFor();
    await snap(6);
    assert.equal(pageErrors.length, 0, pageErrors.join('\n'));
    const mobile = await setup(browser, { theme: 'paper', workspaceLayout: 'lfn' }, { width: 390, height: 844 });
    mobile.page.setDefaultTimeout(20000);
    try {
      await mobile.page.goto(`${baseURL}/profile#profile-tutorials`);
      await mobile.page.locator('[data-tutorial-id="outpaint"]').getByRole('button', { name: /手把手教程$/ }).click();
      await mobile.page.waitForURL('**/image');
      await mobile.page.locator('.feature-tutorial-panel h2').getByText('选择重绘模式并上传源图', { exact: true }).waitFor();
      await mobile.page.getByRole('button', { name: '收起说明，继续操作', exact: true }).first().click();
      await mobile.page.getByRole('button', { name: '生成模式', exact: true }).click();
      await mobile.page.getByRole('option', { name: /局部重绘/ }).click();
      const mobileInput = mobile.page.locator('.mobile-studio-reference-panel input[type="file"]').first();
      await mobileInput.setInputFiles({ name: 'outpaint-mobile-practice.png', mimeType: 'image/png', buffer: source });
      await mobile.page.waitForFunction(() => document.querySelector('[data-tutorial-source-ready="true"]'));
      await mobile.page.getByRole('button', { name: '展开教程说明', exact: true }).click();
      await mobile.page.locator('.feature-tutorial-panel footer').getByRole('button', { name: /下一步/ }).click();
      await mobile.page.locator('.feature-tutorial-panel h2').getByText('打开无限画布', { exact: true }).waitFor();
      await mobile.page.waitForFunction(() => document.querySelector('[data-feature-tutorial-target="true"]')?.getAttribute('data-tutorial-editor') === 'inpaint');
      assert.equal(await mobile.page.locator('[data-feature-tutorial-target="true"]').getAttribute('data-tutorial-editor'), 'inpaint', 'Mobile highlights its available mask-editor entry');
      await mobile.page.screenshot({ path: path.join(mobileOutput, 'mobile-entry.png'), animations: 'disabled' });
      await mobile.page.locator('button[data-tutorial-editor="inpaint"]:visible').first().click();
      await mobile.page.waitForURL('**/image/editor?**');
      const mobileDraft = new URL(mobile.page.url()).searchParams.get('draftId');
      assert(mobileDraft, 'Mobile source also persists as an editor draft');
      assert.match(await mobile.page.locator('.feature-tutorial-status').innerText(), /已进入编辑器.*无限画布/);
      await mobile.page.locator('.editor-mode-tabs').getByRole('button', { name: '无限画布', exact: true }).click();
      await mobile.page.waitForFunction(() => new URL(location.href).searchParams.get('mode') === 'canvas');
      assert.equal(new URL(mobile.page.url()).searchParams.get('draftId'), mobileDraft, 'Manual mode switch keeps the uploaded source draft');
      await mobile.page.screenshot({ path: path.join(mobileOutput, 'mobile-canvas.png'), animations: 'disabled' });
      await advanceTutorial(mobile.page);
      await mobile.page.locator('.feature-tutorial-panel h2').getByText('把生成框移到画面外', { exact: true }).waitFor();
      assert.equal(new URL(mobile.page.url()).searchParams.get('mode'), 'canvas', 'Advancing keeps the intended canvas mode');
      await mobile.page.screenshot({ path: path.join(mobileOutput, 'mobile-frame-step.png'), animations: 'disabled' });
      await mobile.page.getByRole('button', { name: '退出教程，返回个人资料的教程中心', exact: true }).click();
      await mobile.page.waitForURL('**/profile#profile-tutorials');
      await mobile.page.getByRole('status').filter({ hasText: '已退出「扩图与无限画布」' }).waitFor();
      await mobile.page.screenshot({ path: path.join(mobileOutput, 'mobile-return.png'), animations: 'disabled' });
      mobileModeSwitch = { passed: true, sourceRetained: true, nextStep: true, exitReturnedToProfile: true, evidence: mobileOutput };
    } finally { await mobile.context.close(); }
    const precondition = await setup(browser, { theme: 'paper', workspaceLayout: 'lfn' }, { width: 1440, height: 1000 });
    precondition.page.setDefaultTimeout(20000);
    try {
      await precondition.page.goto(`${baseURL}/profile#profile-tutorials`);
      await precondition.page.locator('[data-tutorial-id="outpaint"]').getByRole('button', { name: /手把手教程$/ }).click();
      await precondition.page.waitForURL('**/image');
      await precondition.page.getByRole('button', { name: '收起说明，继续操作', exact: true }).first().click();
      await precondition.page.getByRole('button', { name: /当前.*点击选择生成模式/ }).click();
      const inpaintMode = precondition.page.getByRole('dialog', { name: '选择生成模式', exact: true }).getByRole('button').filter({ hasText: /局部重绘/ }).first();
      await inpaintMode.click();
      await precondition.page.getByRole('button', { name: '展开教程说明', exact: true }).click();
      await precondition.page.locator('.feature-tutorial-panel footer').getByRole('button', { name: /下一步/ }).click();
      await precondition.page.locator('.feature-tutorial-panel h2').getByText('打开无限画布', { exact: true }).waitFor();
      await precondition.page.waitForFunction(() => document.querySelector('[data-feature-tutorial-target="true"]'));
      let highlighted = precondition.page.locator('[data-feature-tutorial-target="true"]');
      assert(await highlighted.evaluate(element => Boolean(element.matches('[data-tutorial="source"], .mobile-studio-reference-panel'))), 'Without a source image, step 2 highlights the image upload/reference area');
      assert.equal(await precondition.page.locator('button[data-tutorial-editor="canvas"][disabled][data-feature-tutorial-target="true"]').count(), 0, 'A disabled editor button is never spotlighted as the next action');
      await precondition.page.screenshot({ path: path.join(mobileOutput, 'source-unready-highlight.png'), animations: 'disabled' });
      const regressionImage = await sharp(source).png().toBuffer();
      await precondition.page.locator('[data-tutorial="source"] input[type="file"]').first().setInputFiles({ name: 'outpaint-ready.png', mimeType: 'image/png', buffer: regressionImage });
      await precondition.page.waitForFunction(() => document.querySelector('[data-tutorial-source-ready="true"]'));
      await precondition.page.waitForFunction(() => document.querySelector('[data-feature-tutorial-target="true"]')?.getAttribute('data-tutorial-editor') === 'canvas');
      highlighted = precondition.page.locator('[data-feature-tutorial-target="true"]');
      assert.equal(await highlighted.getAttribute('data-tutorial-editor'), 'canvas', 'After upload, the same step spotlights the enabled canvas editor button');
      await precondition.page.screenshot({ path: path.join(mobileOutput, 'source-ready-highlight.png'), animations: 'disabled' });
    } finally { await precondition.context.close(); }
    fs.writeFileSync(path.join(output, 'audit-results.json'), JSON.stringify({ passed: true, desktop: { viewport: '1440x1000', steps: 6, sourceDraftId: draftId, interceptedOutpaintingCalls: externalWrites.length, completedAndReturned: true }, mobile: { viewport: '390x844', entry: 'inpaint button spotlight verified', sourceRetained: true, modeSwitch: mobileModeSwitch }, sourceReadinessRegression: { beforeUpload: 'source upload/reference area highlighted; disabled editor button not targeted', afterUpload: 'enabled canvas editor button highlighted' }, networkRequests: requests.map(item => `${item.method} ${item.path}`), pageErrors }, null, 2));
    console.log(`PASS desktop six-step outpaint flow; mobile entry/source retention verified; mobile canvas mode switch ${mobileModeSwitch.passed ? 'PASS' : 'BLOCKED'}: ${mobileModeSwitch.issue || 'ok'}`);
  } catch (error) {
    await page.screenshot({ path: path.join(mobileOutput, 'desktop-failure.png'), animations: 'disabled' }).catch(() => {});
    fs.writeFileSync(path.join(mobileOutput, 'desktop-failure.txt'), `${error.stack || error.message}\n\nURL: ${page.url()}\n\n${await page.locator('body').innerText().catch(() => '')}`);
    fs.writeFileSync(path.join(mobileOutput, 'audit-failure-results.json'), JSON.stringify({ passed: false, error: error.stack || error.message, networkRequests: requests.map(item => `${item.method} ${item.path}`), pageErrors }, null, 2));
    throw error;
  } finally {
    await context.close();
    await browser.close();
  }
})().catch(error => { console.error(error.stack || error.message); process.exitCode = 1; });
