import { mkdtemp } from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

vi.mock("@/lib/session", () => ({ getSession: vi.fn() }));
vi.mock("@/lib/admin-auth", () => ({ requireAdmin: vi.fn() }));
vi.mock("@/lib/gallery", () => ({ getGalleryItem: vi.fn() }));
const original = process.env.LFN_DATA_DIR;
beforeEach(async () => { process.env.LFN_DATA_DIR = await mkdtemp(path.join(os.tmpdir(), "lfn-gallery-comments-")); vi.resetModules(); });
afterEach(() => { if (original == null) delete process.env.LFN_DATA_DIR; else process.env.LFN_DATA_DIR = original; vi.restoreAllMocks(); });
function session(id: number) { return { userId: id, username: `user-${id}`, displayName: `用户 ${id}`, upstreamCookie: "", expiresAt: Date.now() + 3600_000 }; }
describe("gallery comment permissions and notifications", () => {
  it("denies anonymous writes and pending-work access, while allowing administrator moderation", async () => {
    const { getSession } = await import("@/lib/session");
    const { requireAdmin } = await import("@/lib/admin-auth");
    const { getGalleryItem } = await import("@/lib/gallery");
    const { galleryComments } = await import("@/lib/gallery-comments");
    const { GET, POST, PATCH } = await import("@/app/api/gallery/[id]/comments/route");
    const { DELETE } = await import("@/app/api/gallery/[id]/comments/[commentId]/route");
    const context = { params: Promise.resolve({ id: "work" }) };
    const work = { id: "work", ownerId: 1, title: "作品", status: "approved" };
    vi.mocked(getGalleryItem).mockResolvedValue(work as never);
    vi.mocked(getSession).mockResolvedValue(null);
    vi.mocked(requireAdmin).mockResolvedValue({ error: "仅管理员可用" });
    expect((await POST(new Request("http://localhost", { method: "POST", body: JSON.stringify({ content: "x" }) }), context)).status).toBe(401);
    const root = await galleryComments.createComment({ resourceId: "work", authorId: 7, authorName: "评论者", content: "root" });
    const reply = await galleryComments.createComment({ resourceId: "work", authorId: 8, authorName: "回复者", content: "reply", parentId: root.id });
    vi.mocked(getSession).mockResolvedValue(session(9));
    expect((await PATCH(new Request("http://localhost", { method: "PATCH", body: JSON.stringify({ action: "pin", commentId: root.id, pinned: true }) }), context)).status).toBe(403);
    vi.mocked(getGalleryItem).mockResolvedValue({ ...work, status: "pending" } as never);
    expect((await GET(new Request("http://localhost"), context)).status).toBe(404);
    vi.mocked(requireAdmin).mockResolvedValue({ session: session(9) } as never);
    const response = await GET(new Request("http://localhost"), context);
    expect(response.status).toBe(200);
    expect(response.headers.get("cache-control")).toBe("private, no-store");
    expect((await response.json()).canModerate).toBe(true);
    const deleted = await DELETE(new Request("http://localhost"), { params: Promise.resolve({ id: "work", commentId: root.id }) });
    expect((await deleted.json()).deletedIds).toEqual(expect.arrayContaining([root.id, reply.id]));
  });
  it("uses the session author, notifies the owner and author, supports votes and cascades owner moderation", async () => {
    const { getSession } = await import("@/lib/session");
    const { requireAdmin } = await import("@/lib/admin-auth");
    const { getGalleryItem } = await import("@/lib/gallery");
    vi.mocked(getGalleryItem).mockResolvedValue({ id: "work", ownerId: 1, title: "作品", status: "approved" } as never);
    vi.mocked(requireAdmin).mockResolvedValue({ error: "仅管理员可用" });
    vi.mocked(getSession).mockResolvedValue(session(7));
    const { POST, GET, PATCH } = await import("@/app/api/gallery/[id]/comments/route");
    const context = { params: Promise.resolve({ id: "work" }) };
    const request = (body: unknown, method = "POST") => new Request("http://localhost", { method, body: JSON.stringify(body) });
    const first = await POST(request({ content: "评论", authorId: 1 }), context);
    expect(first.status).toBe(200);
    const { item: parent } = await first.json();
    expect(parent.authorId).toBe(7);
    const { listUserNotifications } = await import("@/lib/notifications");
    expect((await listUserNotifications(1)).items).toHaveLength(1);
    expect((await listUserNotifications(7)).items).toHaveLength(1);
    vi.mocked(getSession).mockResolvedValue(session(8));
    const { item: reply } = await (await POST(request({ content: "回复", parentId: parent.id }), context)).json();
    expect((await listUserNotifications(7)).items.some(item => item.type === "gallery-reply")).toBe(true);
    expect((await PATCH(request({ commentId: parent.id, action: "vote", vote: "up" }, "PATCH"), context)).status).toBe(200);
    expect((await (await GET(new Request("http://localhost"), context)).json()).items.find((item: { id: string }) => item.id === parent.id)).toMatchObject({ likes: 1, myVote: "up" });
    const { DELETE } = await import("@/app/api/gallery/[id]/comments/[commentId]/route");
    const removeContext = { params: Promise.resolve({ id: "work", commentId: parent.id }) };
    expect((await DELETE(new Request("http://localhost"), removeContext)).status).toBe(403);
    vi.mocked(getSession).mockResolvedValue(session(1));
    const deleted = await DELETE(new Request("http://localhost"), removeContext);
    expect((await deleted.json()).deletedIds).toEqual(expect.arrayContaining([parent.id, reply.id]));
    expect((await (await GET(new Request("http://localhost"), context)).json()).items).toEqual([]);
    expect((await listUserNotifications(7)).items).toEqual([]);
  });
  it("persists personal hiding and blocking without changing other users' preferences", async () => {
    const { setCommentPreference, getCommentPreferences } = await import("@/lib/comment-preferences");
    await setCommentPreference(7, { commentId: "comment", hidden: true });
    await setCommentPreference(7, { authorId: 8, hidden: true });
    expect(await getCommentPreferences(7)).toEqual({ hiddenIds: ["comment"], blockedAuthorIds: [8] });
    expect(await getCommentPreferences(9)).toEqual({ hiddenIds: [], blockedAuthorIds: [] });
    await setCommentPreference(7, { authorId: 8, hidden: false });
    expect((await getCommentPreferences(7)).blockedAuthorIds).toEqual([]);
  });
});
